import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'/home/mathis/openclaw-workspace/option-pricing-workbench/web/node_modules/playwright-core');
const base=(process.env.BASE_URL||'http://127.0.0.1:18929').replace(/\/$/,'');
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',headless:true,args:['--no-sandbox','--disable-dev-shm-usage','--disable-gpu','--renderer-process-limit=2']});
let checks=0;
const ok=(value,label)=>{assert.ok(value,label);checks++;};
try {
  const context=await browser.newContext({viewport:{width:1440,height:1000}});
  const page=await context.newPage(),errors=[];
  page.on('pageerror',error=>{errors.push(error.message);console.error('BROWSER ERROR at '+page.url()+': '+error.stack);});
  const field=key=>page.locator(`[data-finance-key="${key}"]`);
  const slider=key=>page.locator(`[data-finance-slider="${key}"]`);
  const curve=()=>page.locator('.finance-line').getAttribute('points');
  const baseline=()=>page.locator('.finance-baseline').getAttribute('points');
  const visibleLab=()=>page.locator('.deck-lab').isVisible();
  const jump=async index=>{await page.locator('[data-action="overview"]').click();await page.locator(`[data-slide-jump="${index}"]`).click();};
  const viewportFits=async label=>ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),label);
  const shot=async name=>{if(process.env.SCREENSHOTS)await page.screenshot({path:`/tmp/volto-finance-live-${name}.png`,fullPage:name!=='projector-1280'});};
  await page.goto(base+'/finanzen/');
  await field('subscription').waitFor();
  ok((await page.locator('.finance-kpis').innerText()).includes('15’900'),'source baseline annual cash');
  ok((await page.locator('.finance-kpis').innerText()).includes('60’000'),'source baseline investment');
  ok(await slider('subscription').count()===1,'subscription has a slider');
  const initialCurve=await curve(),initialBase=await baseline();
  await field('subscription').fill('35');
  ok((await page.locator('.finance-kpis').innerText()).includes('23’100'),'numeric field changes annual cash immediately');
  ok(await slider('subscription').inputValue()==='35','numeric field synchronizes slider');
  ok(initialCurve!==await curve(),'current cashflow curve changes coordinates');
  ok(await baseline()!==null&&initialBase!==null,'baseline comparison remains on chart');
  await slider('subscription').focus();await page.keyboard.press('ArrowLeft');
  ok(await field('subscription').inputValue()==='34','slider keyboard synchronizes numeric field');
  ok((await page.locator('.finance-kpis').innerText()).includes('22’380'),'slider keyboard recalculates annual cash');
  const validCurve=await curve();
  await field('subscription').fill('');
  ok(await field('subscription').getAttribute('aria-invalid')==='true','blank field invalid');
  ok(await curve()===validCurve,'blank input keeps last valid chart');
  await field('subscription').fill('-1');
  ok(await field('subscription').getAttribute('aria-invalid')==='true','negative field invalid');
  ok(await curve()===validCurve,'invalid input keeps last valid chart');
  await field('subscription').fill('35');
  await page.reload();await field('subscription').waitFor();
  ok(await field('subscription').inputValue()==='35','scenario persists on reload');
  await page.locator('[data-finance-preset]').selectOption('cham');
  ok((await page.locator('.finance-kpis').innerText()).includes('17’400'),'Cham uses separate baseline investment');
  await field('feePerBox').fill('65');
  await page.locator('[data-finance-preset]').selectOption('zurich');
  ok(await field('subscription').inputValue()==='35','Zürich scenario retained across model switching');
  await page.locator('[data-finance-preset]').selectOption('cham');
  ok(await field('feePerBox').inputValue()==='65','Cham scenario retained across model switching');
  await field('evShare').fill('0');
  ok((await page.locator('.finance-kpis').innerText()).includes('Nicht erreicht'),'zero EV scenario has no payback');
  ok(!/NaN|Infinity/.test(await page.locator('.finance').innerText()),'zero demand has finite output');
  await page.locator('[data-finance-reset]').click();
  ok(await field('evShare').inputValue()==='11.9','Cham reset restores its source assumptions');
  await page.locator('[data-finance-preset]').selectOption('zurich');
  await shot('website-1440');

  await page.goto(base+'/praesentation/');await page.waitForFunction(()=>window.voltoPresentationReady);
  const response=await page.request.get(base+'/presentation-data.json'),data=await response.json();
  ok(data.slides.length===17,'authorized 17-slide manifest retains original content');
  ok(await page.locator('[data-slide-jump]').count()===17,'all original slides still selectable');
  await jump(13);
  const original=await page.locator('.deck-artwork').getAttribute('src');
  ok(original===data.slides[13].image,'finance source slide remains original artwork');
  await page.locator('[data-action="next"]').click();
  ok(await visibleLab(),'next after slide 14 enters interactive step');
  ok(await field('subscription').inputValue()==='35','presentation uses saved website assumptions');
  ok(await page.locator('.deck-lab').getAttribute('aria-modal')!== 'true','interactive step is not a blocking modal');
  await field('subscription').focus();await page.keyboard.press('ArrowRight');
  ok(await visibleLab(),'input arrow does not advance presentation');
  const presentationCurve=await curve();
  await field('subscription').fill('15');
  ok((await page.locator('.finance-kpis').innerText()).includes('8’700'),'presentation scenario recalculates');
  ok(await curve()!==presentationCurve,'presentation graph changes coordinates live');
  ok(await page.locator('.deck-artwork').getAttribute('src')===original,'live edits leave original artwork untouched');
  await page.locator('[data-action="next"]').click();
  ok(!(await visibleLab()),'next exits live step');
  ok(await page.locator('.deck-slide').getAttribute('data-slide')==='14','next resumes source slide 15');
  await page.locator('[data-action="prev"]').click();
  ok(await visibleLab(),'previous from slide 15 revisits live step');
  await page.locator('[data-action="prev"]').click();
  ok(await page.locator('.deck-slide').getAttribute('data-slide')==='13','previous from live returns source slide 14');
  ok(!(await visibleLab()),'source view restored');
  await page.locator('[data-action="finance"]').click();
  ok(await visibleLab(),'toolbar opens live scenario directly');
  await page.locator('[data-finance-preset]').selectOption('cham');
  ok(await field('feePerBox').isVisible(),'both models available inside presentation');
  await page.locator('[data-finance-preset]').selectOption('zurich');
  await page.locator('[data-finance-reset]').click();
  ok(await field('subscription').inputValue()==='25','presentation reset restores source baseline');
  await page.locator('[data-action="finance-close"]').click();
  ok(!(await visibleLab()),'return-to-slide action restores source view');
  ok(await page.locator('.deck-artwork').getAttribute('src')===original,'return preserves same source slide');

  await page.setViewportSize({width:1280,height:720});
  await page.locator('[data-action="fullscreen"]').click();
  ok(await page.locator('.deck').evaluate(e=>e.classList.contains('deck-expanded')),'fullscreen entered');
  await page.locator('[data-action="finance"]').click();
  await field('subscription').fill('30');
  ok((await page.locator('.finance-kpis').innerText()).includes('19’500'),'fullscreen edit recalculates');
  ok(await page.locator('.deck').evaluate(e=>e.classList.contains('deck-expanded')),'live edit retains fullscreen');
  await viewportFits('fullscreen live has no horizontal overflow at 1280x720');
  const bounds=await page.locator('.finance-chart').boundingBox();
  ok(bounds&&bounds.x>=0&&bounds.x+bounds.width<=1281,'projector chart fits horizontal stage');
  const presentationFit=await page.locator('.deck-lab').evaluate(lab=>{
    const r=lab.getBoundingClientRect();
    return ['.finance-quick','.finance-chart-panel','.finance-kpis'].every(selector=>{const box=lab.querySelector(selector).getBoundingClientRect();return box.top>=r.top&&box.bottom<=r.bottom;});
  });
  ok(presentationFit,'four levers, chart and all KPI values fit the projector without scrolling');
  await shot('projector-1280');
  await page.keyboard.press('Escape');
  ok(!(await visibleLab()),'Escape restores original slide');
  ok(await page.locator('.deck').evaluate(e=>e.classList.contains('deck-expanded')),'first Escape retains fullscreen');
  await page.keyboard.press('Escape');
  await page.waitForFunction(()=>!document.querySelector('.deck').classList.contains('deck-expanded'));
  ok(!(await page.locator('.deck').evaluate(e=>e.classList.contains('deck-expanded'))),'second Escape exits fullscreen');

  for(const width of [360,768,1440]) {
    await page.setViewportSize({width,height:1000});
    await page.goto(base+'/finanzen/');await field('subscription').waitFor();
    await viewportFits('finance page width '+width);
    const inputs=await page.locator('.finance input:visible,.finance select:visible,.finance button:visible').evaluateAll(nodes=>nodes.map(el=>{const r=el.getBoundingClientRect();return {h:r.height,w:r.width,label:el.getAttribute('aria-label')||el.id};}));
    ok(inputs.every(x=>x.h>=44&&x.w>=44),'finance controls at least 44px targets '+width);
    await shot('website-'+width);
    for(const route of ['/praesentation/','/']) {
      await page.goto(base+route);await page.waitForFunction(()=>window.voltoPresentationReady);
      await page.locator('[data-action="finance"]').click();
      ok(await field('subscription').isVisible(),'live controls visible '+route+' '+width);
      await viewportFits('live stage width '+route+' '+width);
      await shot((route==='/'?'embedded':'deck')+'-'+width);
      await page.locator('[data-action="finance-close"]').click();
    }
  }
  await page.goto(base+'/finanzen/?preset=cham');await field('feePerBox').waitFor();
  await field('feePerBox').fill('65');
  ok((await page.locator('[data-finance-present]').getAttribute('href')).includes('preset=cham'),'present link carries selected Cham model');
  await page.locator('[data-finance-present]').click();await page.waitForFunction(()=>window.voltoPresentationReady);
  ok(await visibleLab(),'finance page link opens interactive step');
  ok(await page.locator('[data-finance-preset]').inputValue()==='cham','finance page link preserves Cham selection');
  ok(await field('feePerBox').inputValue()==='65','finance page link preserves edited Cham assumptions');
  await page.goto(base+'/praesentation/?slide=14&live=1');await page.waitForFunction(()=>window.voltoPresentationReady);
  ok(await visibleLab(),'direct presentation link opens live step');
  await page.goto(base+'/praesentation/?print=1');await page.waitForFunction(()=>window.voltoPresentationReady);
  ok(await page.locator('.deck-stage').count()===17,'print version retains 17 original slides only');
  ok(errors.length===0,'no browser errors: '+errors.join(';'));
  console.log(`PASS ${checks} financial redesign / live presentation browser checks on ${base}`);
} finally {await browser.close();}
